package com.knittrac.app.domain.entity

/**
 * Агрегированная статистика работы за один день.
 *
 * Эта сущность представляет собой результат агрегации всех сессий
 * за конкретный день. Используется для построения графиков активности
 * и отображения статистики пользователя.
 *
 * @param dayTimestamp Временная метка начала дня (00:00:00) в миллисекундах.
 *        Вычисляется как (startTimestamp / 86400000) * 86400000,
 *        что округляет время до начала суток.
 * @param totalSeconds Общее количество секунд, затраченных на все проекты
 *        в этот день. Суммируется из [Session.durationSeconds] всех сессий.
 *
 * @see Session Сущность сессии, из которой агрегируется статистика.
 */
data class DailyStat(
    val dayTimestamp: Long,
    val totalSeconds: Long
)