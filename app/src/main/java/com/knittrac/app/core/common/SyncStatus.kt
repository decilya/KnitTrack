package com.knittrac.app.core.common

/**
 * Статус синхронизации сущности с облачным сервером.
 *
 * Используется для отслеживания состояния данных в локальной базе данных
 * и определения необходимости отправки изменений на сервер.
 *
 * @see SYNCED Данные синхронизированы с сервером (актуальная версия).
 * @see PENDING Данные изменены локально и ожидают отправки на сервер.
 * @see CONFLICT Обнаружен конфликт версий между локальными и серверными данными.
 */
enum class SyncStatus {
    /** Данные синхронизированы с сервером. */
    SYNCED,

    /** Данные изменены локально и ожидают отправки на сервер (требуется синхронизация). */
    PENDING,

    /** Обнаружен конфликт версий при синхронизации (требуется разрешение конфликта). */
    CONFLICT
}